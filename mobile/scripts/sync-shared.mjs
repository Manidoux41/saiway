import { mkdir, readFile, writeFile } from 'node:fs/promises';

const sources = {
  'locale-format.ts': '../../lib/locale-format.ts',
  'booking-history-note.ts': '../../components/i18n/booking-history-note.ts',
  'interface-copy.ts': '../../components/i18n/interface-copy.ts',
};
const checking = process.argv.includes('--check');
const directory = new URL('../src/lib/shared/', import.meta.url);
if (!checking) await mkdir(directory, { recursive: true });

for (const [name, source] of Object.entries(sources)) {
  const content = '// Generated by npm run sync:shared. Do not edit manually.\n'
    + await readFile(new URL(source, import.meta.url), 'utf8');
  const destination = new URL(name, directory);
  if (checking) {
    if (await readFile(destination, 'utf8') !== content) {
      throw new Error(`Shared mobile copy is outdated: ${name}. Run npm run sync:shared.`);
    }
  } else {
    await writeFile(destination, content);
  }
}
console.log(checking ? 'Shared copies match Next.js sources.' : 'Shared copies updated for standalone mobile builds.');
