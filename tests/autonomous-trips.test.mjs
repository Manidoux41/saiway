import { test } from 'node:test';
import { createHmac } from 'node:crypto';
import { assert, request, setup, createAccount } from './helpers.mjs';

test('anonymous autonomous trip preserves selected GPS and signed route, is idempotent and enforces ownership', async () => {
  const ctx = await setup();
  try {
    const driver = await createAccount(ctx, 'DRIVER');
    const other = await createAccount(ctx, 'DRIVER', 'other');
    const customer = await createAccount(ctx, 'CUSTOMER');
    const vehicle = await ctx.prisma.vehicle.create({ data: { name: ctx.prefix, plate: ctx.prefix, seats: 4, iconCategory: 'SEDAN' } });
    const selection = { vehicleId: vehicle.id, fromAddress: 'Exact departure label', toAddress: 'Exact destination label', fromPoint: { latitude: 13.3601234, longitude: 103.8501234 }, toPoint: { latitude: 13.3701234, longitude: 103.8601234 } };
    const previewBody = { action: 'preview', selection };
    assert.equal((await request('/api/driver/bookings', 'POST', previewBody)).status, 403);
    assert.equal((await request('/api/driver/bookings', 'POST', previewBody, customer.cookie)).status, 403);
    assert.equal((await request('/api/driver/bookings', 'POST', previewBody, ctx.cookie)).status, 403);
    assert.equal((await request('/api/driver/bookings', 'POST', { action: 'preview', selection: { ...selection, vehicleId: 'missing' } }, driver.cookie)).status, 422);
    const preview = await request('/api/driver/bookings', 'POST', previewBody, driver.cookie);
    assert.equal(preview.status, 200);
    assert.equal(preview.data.fareDetails.mode, 'CITY');
    assert.equal(preview.data.priceCents, 325);
    assert.equal(preview.data.route.durationSeconds, 600);
    assert.deepEqual(preview.data.route.from, selection.fromPoint);
    const body = { quoteToken: preview.data.token, passengers: 1 };
    const forged = preview.data.token.split('.');
    const payload = JSON.parse(Buffer.from(forged[0], 'base64url'));
    const expiredPayload = Buffer.from(JSON.stringify({ ...payload, expiresAt: Date.now() - 1 })).toString('base64url');
    const expiredToken = `${expiredPayload}.${createHmac('sha256', process.env.AUTH_SECRET).update(`autonomous-trip:${expiredPayload}`).digest('base64url')}`;
    assert.equal((await request('/api/driver/bookings', 'POST', { ...body, quoteToken: expiredToken }, driver.cookie)).status, 409);
    payload.priceCents = 1;
    const tampered = `${Buffer.from(JSON.stringify(payload)).toString('base64url')}.${forged[1]}`;
    assert.equal((await request('/api/driver/bookings', 'POST', { ...body, quoteToken: tampered }, driver.cookie)).status, 400);
    assert.equal((await request('/api/driver/bookings', 'POST', body, other.cookie)).status, 400);
    assert.equal((await request('/api/driver/bookings', 'POST', { ...body, agreedPriceCents: 1, priceReason: 'forged' }, driver.cookie)).status, 400);
    assert.equal((await request('/api/driver/bookings', 'POST', { ...body, passengers: 5 }, driver.cookie)).status, 400);
    const starts = await Promise.all([request('/api/driver/bookings', 'POST', body, driver.cookie), request('/api/driver/bookings', 'POST', body, driver.cookie)]);
    assert.ok(starts.some((item) => [200, 201].includes(item.status)));
    assert.ok(starts.every((item) => [200, 201, 409].includes(item.status)));
    const created = starts.find((item) => item.data.booking)?.data.booking;
    assert.equal(created.customer, null);
    assert.equal(created.originType, 'DRIVER');
    assert.equal(created.status, 'TRIP_STARTED');
    assert.equal(created.estimatedPriceCents, 325);
    assert.equal(created.payments.length, 0);
    assert.ok(created.startedAt);
    const retry = await request('/api/driver/bookings', 'POST', body, driver.cookie);
    assert.equal(retry.status, 200);
    assert.equal(retry.data.booking.id, created.id);
    assert.equal((await request('/api/driver/bookings', 'POST', { ...body, quoteToken: expiredToken }, driver.cookie)).data.booking.id, created.id);
    assert.equal(await ctx.prisma.booking.count({ where: { startRequestId: payload.requestId } }), 1);
    const stored = await ctx.prisma.booking.findUniqueOrThrow({ where: { id: created.id } });
    assert.deepEqual(stored.routeDetails.from, selection.fromPoint);
    assert.deepEqual(stored.routeDetails.to, selection.toPoint);
    assert.equal(stored.estimatedPriceCents, 325);
    const profile = await ctx.prisma.driverProfile.findUniqueOrThrow({ where: { userId: driver.id } });
    await ctx.prisma.driverLocation.create({ data: { driverId: profile.id, bookingId: created.id, latitude: selection.fromPoint.latitude, longitude: selection.fromPoint.longitude, accuracy: 5 } });
    const fleet = await request('/api/admin/fleet-locations', 'GET', undefined, ctx.cookie);
    assert.equal(fleet.status, 200);
    assert.equal(fleet.data.drivers.find((item) => item.id === profile.id).target.address, 'GPS: 13.3701234, 103.8601234');
    assert.equal((await request('/api/bookings', 'GET', undefined, customer.cookie)).data.bookings.length, 0);
    assert.equal((await request(`/api/bookings/${created.id}/location`, 'GET', undefined, customer.cookie)).status, 404);
    assert.equal((await request('/api/driver/bookings', 'GET', undefined, other.cookie)).data.bookings.length, 0);
    assert.ok((await request('/api/admin/bookings', 'GET', undefined, ctx.cookie)).data.bookings.some((item) => item.id === created.id));
    const nextPreview = await request('/api/driver/bookings', 'POST', previewBody, other.cookie);
    assert.equal((await request('/api/driver/bookings', 'POST', { quoteToken: nextPreview.data.token, passengers: 1 }, other.cookie)).status, 409);
    assert.equal((await request('/api/driver/bookings', 'PATCH', { id: created.id, status: 'TRIP_COMPLETED' }, other.cookie)).status, 404);
    const incomplete = await request('/api/driver/bookings', 'PATCH', { id: created.id, status: 'TRIP_COMPLETED' }, driver.cookie);
    assert.equal(incomplete.status, 409);
    const done = await request('/api/driver/bookings', 'PATCH', { id: created.id, status: 'TRIP_COMPLETED', confirmEstimatedDistance: true, observations: 'Passenger safely dropped off', finalPoint: selection.toPoint }, driver.cookie);
    assert.equal(done.status, 200);
    assert.equal(done.data.booking.estimatedPriceCents, 325);
    assert.equal(done.data.booking.priceCents, 325);
    assert.equal(done.data.booking.driverObservations, 'Passenger safely dropped off');
    assert.ok(done.data.booking.completedAt);
    assert.ok(done.data.booking.actualDurationSeconds >= 0);
    const ended = await ctx.prisma.booking.findUniqueOrThrow({ where: { id: created.id } });
    assert.equal(Number(ended.finalLatitude), selection.toPoint.latitude);
    assert.equal(Number(ended.finalLongitude), selection.toPoint.longitude);
    assert.ok(done.data.booking.statusHistory.some((event) => event.note.includes('driver confirmed road estimate')));
    const manual = await request('/api/driver/bookings', 'POST', { action: 'preview', selection: { vehicleId: vehicle.id, fromAddress: 'Manual departure', toAddress: 'Manual destination' } }, driver.cookie);
    assert.equal(manual.status, 200);
    assert.deepEqual(Object.keys(manual.data.route.from).sort(), ['latitude', 'longitude']);
    assert.deepEqual(Object.keys(manual.data.route.to).sort(), ['latitude', 'longitude']);
    const manualStart = await request('/api/driver/bookings', 'POST', { quoteToken: manual.data.token, passengers: 1 }, driver.cookie);
    assert.equal(manualStart.status, 201);
    assert.equal(manualStart.data.booking.fromAddress, 'Manual departure');
  } finally { await ctx.cleanup(); }
});
