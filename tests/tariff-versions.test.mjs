import { test } from 'node:test';
import { assert, request, setup, createAccount } from './helpers.mjs';
import { defaultFarePolicy, farePolicyKey } from '../lib/fare-policy.ts';

test('scheduled immutable tariffs preserve existing estimates and justified corrections survive finalization', async () => {
  const ctx = await setup();
  try {
    const driver = await createAccount(ctx, 'DRIVER');
    const customer = await createAccount(ctx, 'CUSTOMER');
    const vehicle = await ctx.prisma.vehicle.create({ data: { name: ctx.prefix, plate: ctx.prefix, seats: 4, iconCategory: 'SEDAN' } });
    const previewBody = { action: 'preview', selection: { vehicleId: vehicle.id, fromAddress: 'GPS: 13.36, 103.85', toAddress: 'GPS: 13.37, 103.86' } };
    const preview = await request('/api/driver/bookings', 'POST', previewBody, driver.cookie);
    const booking = await request('/api/driver/bookings', 'POST', { quoteToken: preview.data.token, passengers: 1 }, driver.cookie);
    assert.equal(booking.status, 201);
    const id = booking.data.booking.id;
    const scheduledPolicy = { ...defaultFarePolicy, cityCentsPerKm: 100, cityPickupCents: 100, cityMinimumCents: 500, khrPerUsd: 4100 };
    const scheduled = { entity: 'setting', data: { key: farePolicyKey, value: scheduledPolicy, effectiveAt: new Date(Date.now() + 86400000).toISOString() } };
    assert.equal((await request('/api/admin/management', 'POST', scheduled)).status, 403);
    assert.equal((await request('/api/admin/management', 'POST', scheduled, customer.cookie)).status, 403);
    const future = await request('/api/admin/management', 'POST', scheduled, ctx.cookie);
    assert.equal(future.status, 201);
    assert.equal((await request('/api/driver/bookings', 'POST', previewBody, driver.cookie)).data.priceCents, 325);
    const currentPolicy = { ...defaultFarePolicy, cityPickupCents: 100, cityMinimumCents: 500, vehicleSurcharges: { SEDAN: 50 }, exceptionalSurcharges: [{ label: 'Holiday', cents: 100 }], khrPerUsd: 4100 };
    const current = await request('/api/admin/management', 'POST', { entity: 'setting', data: { key: farePolicyKey, value: currentPolicy } }, ctx.cookie);
    assert.equal(current.status, 201);
    const management = await request('/api/admin/management', 'GET', undefined, ctx.cookie);
    assert.equal(management.data.farePolicy.cityCentsPerKm, 65);
    assert.equal(management.data.farePolicy.khrPerUsd, 4100);
    assert.equal(management.data.tariffHistory.length, 3);
    assert.equal(management.data.tariffHistory[0].id, future.data.item.id);
    assert.equal(management.data.pricing.some((row) => row.id === current.data.item.id), false);
    assert.equal((await request('/api/admin/management', 'PATCH', { entity: 'pricing', id: current.data.item.id, data: { amountCents: 1 } }, ctx.cookie)).status, 400);
    assert.equal((await request('/api/admin/management', 'DELETE', { entity: 'pricing', id: current.data.item.id }, ctx.cookie)).status, 400);
    const quoted = await request('/api/driver/bookings', 'POST', previewBody, driver.cookie);
    assert.equal(quoted.data.priceCents, 575);
    assert.equal(quoted.data.fareDetails.tariffId, current.data.item.id);
    assert.equal(quoted.data.fareDetails.policy.khrPerUsd, 4100);
    const original = await ctx.prisma.booking.findUniqueOrThrow({ where: { id } });
    assert.equal(original.estimatedPriceCents, 325);
    assert.equal(original.fareDetails.policy.cityPickupCents, 0);
    assert.equal((await request('/api/admin/bookings', 'PATCH', { id, finalPriceCents: 425 }, ctx.cookie)).status, 400);
    assert.equal((await request('/api/admin/bookings', 'PATCH', { id, priceCents: 425 }, ctx.cookie)).status, 409);
    const correction = await request('/api/admin/bookings', 'PATCH', { id, finalPriceCents: 425, priceReason: 'Documented passenger-approved extra stop' }, ctx.cookie);
    assert.equal(correction.status, 200);
    assert.equal(correction.data.booking.estimatedPriceCents, 325);
    assert.equal(correction.data.booking.fareDetails.adjustmentCents, 100);
    const done = await request('/api/driver/bookings', 'PATCH', { id, status: 'TRIP_COMPLETED', confirmEstimatedDistance: true }, driver.cookie);
    assert.equal(done.status, 200);
    assert.equal(done.data.booking.priceCents, 425);
    assert.equal(done.data.booking.estimatedPriceCents, 325);
    assert.equal(done.data.booking.pricingStatus, 'ADMIN_ADJUSTED');
    assert.ok(done.data.booking.statusHistory.some((event) => event.note.includes('Documented passenger-approved')));
    assert.equal((await request('/api/driver/payments', 'POST', { bookingId: id, received: true, collectionMethod: 'CASH' }, driver.cookie)).status, 200);
    const readback = await ctx.prisma.booking.findUniqueOrThrow({ where: { id }, include: { payments: true } });
    assert.equal(readback.payments[0].amountCents, 425);
    assert.equal(readback.fareDetails.policy.cityPickupCents, 0);
    assert.ok(await ctx.prisma.auditLog.findFirst({ where: { entityId: id, action: 'PRICE_ADJUSTMENT' } }));
  } finally { await ctx.cleanup(); }
});
